#!/usr/bin/env node
// Converts data/synthetic_coffee_health_10000.csv into a SQL seed file that
// `supabase db reset` loads automatically (see [db.seed] in supabase/config.toml).
//
// Convierte data/synthetic_coffee_health_10000.csv en un archivo SQL de seed
// que `supabase db reset` carga automáticamente (ver [db.seed] en supabase/config.toml).

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const csvPath = join(root, "data", "synthetic_coffee_health_10000.csv");
const outPath = join(root, "supabase", "seeds", "coffee_health.sql");

const lines = readFileSync(csvPath, "utf8").trim().split(/\r?\n/);
const header = lines.shift().split(",");

const expected = [
  "ID", "Age", "Gender", "Country", "Coffee_Intake", "Caffeine_mg",
  "Sleep_Hours", "Sleep_Quality", "BMI", "Heart_Rate", "Stress_Level",
  "Physical_Activity_Hours", "Health_Issues", "Occupation", "Smoking",
  "Alcohol_Consumption",
];
if (header.join(",") !== expected.join(",")) {
  console.error("Unexpected CSV header / Encabezado CSV inesperado:", header);
  process.exit(1);
}

const text = (v) => `'${v.replace(/'/g, "''")}'`;
const num = (v) => {
  if (!/^-?\d+(\.\d+)?$/.test(v)) throw new Error(`Not a number: ${v}`);
  return v;
};
const bool = (v) => (v === "1" ? "true" : "false");

const rows = lines.map((line) => {
  const c = line.split(",");
  return `(${[
    num(c[0]), num(c[1]), text(c[2]), text(c[3]), num(c[4]), num(c[5]),
    num(c[6]), text(c[7]), num(c[8]), num(c[9]), text(c[10]), num(c[11]),
    text(c[12]), text(c[13]), bool(c[14]), bool(c[15]),
  ].join(",")})`;
});

const columns =
  "id, age, gender, country, coffee_intake, caffeine_mg, sleep_hours, sleep_quality, bmi, heart_rate, stress_level, physical_activity_hours, health_issues, occupation, smoking, alcohol_consumption";

const BATCH = 1000;
let sql = "-- Generated by scripts/generate-seed.mjs. Do not edit by hand.\n";
sql += "truncate table public.coffee_health;\n";
for (let i = 0; i < rows.length; i += BATCH) {
  sql += `insert into public.coffee_health (${columns}) values\n`;
  sql += rows.slice(i, i + BATCH).join(",\n") + ";\n";
}

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, sql);
console.log(`Wrote ${rows.length} rows to ${outPath}`);
